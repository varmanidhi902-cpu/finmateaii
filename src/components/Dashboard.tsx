import { useEffect, useState } from 'react'
import { AlertTriangle, BarChart3, BrainCircuit, Cpu, RotateCw, Sparkles, WifiOff } from 'lucide-react'
import type { CurrencyCode } from '@/lib/currency'
import type { FinanceMetrics, FinancialPlan } from '@/lib/finance'
import { downloadReport } from '@/lib/report'
import { BudgetCard } from './BudgetCard'
import { MonthlySummary } from './MonthlySummary'
import { SavingsRecommendations } from './SavingsRecommendations'

export type DashboardStatus = 'idle' | 'loading' | 'success' | 'error'

interface Props {
  status: DashboardStatus
  plan: FinancialPlan | null
  metrics: FinanceMetrics | null
  currency: CurrencyCode
  isDark: boolean
  error: string | null
  onRetry: () => void
  onUseOffline: () => void
  onNewPlan: () => void
}

export function Dashboard({ status, plan, metrics, currency, isDark, error, onRetry, onUseOffline, onNewPlan }: Props) {
  // Chart.js needs the browser, so charts only render after mount.
  const [mounted, setMounted] = useState(false)
  useEffect(() => setMounted(true), [])

  return (
    <section id="dashboard" className="relative border-y border-slate-200/70 bg-white/50 py-20 dark:border-white/5 dark:bg-white/[0.015]">
      <div className="mx-auto max-w-7xl px-4 sm:px-6 lg:px-8">
        <div className="flex flex-wrap items-end justify-between gap-4">
          <div>
            <p className="text-sm font-semibold uppercase tracking-wider text-indigo-600 dark:text-indigo-400">Dashboard</p>
            <h2 className="mt-2 text-3xl font-bold sm:text-4xl">Your AI financial plan</h2>
          </div>
          {status === 'success' && plan && (
            <span className="inline-flex items-center gap-2 rounded-full border border-slate-200 bg-white px-3 py-1.5 text-xs font-medium text-slate-600 dark:border-white/10 dark:bg-white/5 dark:text-slate-300">
              {plan.source === 'gemini' ? (
                <><Sparkles className="h-3.5 w-3.5 text-violet-500" /> Generated by Gemini AI</>
              ) : (
                <><Cpu className="h-3.5 w-3.5 text-indigo-500" /> FinMate offline analysis</>
              )}
            </span>
          )}
        </div>

        <div className="mt-10">
          {status === 'idle' && <EmptyState />}
          {status === 'loading' && <LoadingState />}
          {status === 'error' && <ErrorState message={error} onRetry={onRetry} onUseOffline={onUseOffline} />}
          {status === 'success' && plan && metrics && mounted && (
            <div className="space-y-6">
              <BudgetCard plan={plan} metrics={metrics} currency={currency} isDark={isDark} />
              <SavingsRecommendations items={plan.recommendations} currency={currency} />
              <MonthlySummary
                plan={plan}
                metrics={metrics}
                currency={currency}
                isDark={isDark}
                onDownload={() => downloadReport(plan, metrics, currency)}
                onNewPlan={onNewPlan}
              />
            </div>
          )}
        </div>
      </div>
    </section>
  )
}

function EmptyState() {
  return (
    <div className="card flex flex-col items-center px-6 py-16 text-center">
      <div className="relative">
        <div className="absolute inset-0 rounded-3xl bg-indigo-400/30 blur-2xl" />
        <span className="relative grid h-16 w-16 place-items-center rounded-2xl bg-gradient-to-br from-indigo-600 to-violet-500 text-white shadow-lg">
          <BarChart3 className="h-8 w-8" />
        </span>
      </div>
      <h3 className="mt-6 text-xl font-bold">Your dashboard is waiting</h3>
      <p className="mt-2 max-w-md text-slate-600 dark:text-slate-400">
        Enter your income, expenses and goals above, then hit <strong>Generate My Financial Plan</strong> to see your budget,
        saving suggestions and monthly report here.
      </p>
      <div className="mt-8 grid w-full max-w-2xl grid-cols-3 gap-3 opacity-60">
        {['Budget Plan', 'Saving Suggestions', 'Monthly Summary'].map((t) => (
          <div key={t} className="rounded-xl border border-dashed border-slate-300 p-4 text-xs font-medium text-slate-500 dark:border-white/15 dark:text-slate-400">
            {t}
          </div>
        ))}
      </div>
      <a href="#advisor" className="mt-8 text-sm font-semibold text-indigo-600 hover:underline dark:text-indigo-400">
        Go to the AI Advisor →
      </a>
    </div>
  )
}

const LOADING_STEPS = ['Reading your income & expenses', 'Comparing with healthy benchmarks', 'Designing your budget split', 'Writing personalised recommendations']

function LoadingState() {
  const [step, setStep] = useState(0)
  useEffect(() => {
    const t = setInterval(() => setStep((s) => Math.min(s + 1, LOADING_STEPS.length - 1)), 900)
    return () => clearInterval(t)
  }, [])

  return (
    <div className="space-y-6" aria-live="polite" aria-busy="true">
      <div className="card flex flex-col items-center gap-5 px-6 py-10 text-center sm:flex-row sm:text-left">
        <div className="relative grid h-16 w-16 shrink-0 place-items-center">
          <span className="absolute inset-0 animate-ping rounded-2xl bg-indigo-400/30" />
          <span className="relative grid h-16 w-16 place-items-center rounded-2xl bg-gradient-to-br from-indigo-600 to-violet-500 text-white">
            <BrainCircuit className="h-8 w-8 animate-pulse" />
          </span>
        </div>
        <div className="flex-1">
          <h3 className="text-lg font-bold">AI is analyzing your finances…</h3>
          <ul className="mt-3 space-y-1.5">
            {LOADING_STEPS.map((s, i) => (
              <li
                key={s}
                className={`flex items-center justify-center gap-2 text-sm transition-colors sm:justify-start ${
                  i <= step ? 'text-navy-900 dark:text-white' : 'text-slate-400 dark:text-slate-600'
                }`}
              >
                <span className={`h-1.5 w-1.5 rounded-full ${i < step ? 'bg-emerald-500' : i === step ? 'animate-pulse bg-indigo-500' : 'bg-slate-300 dark:bg-slate-700'}`} />
                {s}
              </li>
            ))}
          </ul>
        </div>
      </div>
      <div className="grid gap-6 md:grid-cols-2">
        {[0, 1].map((i) => (
          <div key={i} className="card space-y-4 p-6">
            <div className="skeleton h-5 w-40" />
            <div className="skeleton h-40 w-full" />
            <div className="skeleton h-4 w-3/4" />
            <div className="skeleton h-4 w-1/2" />
          </div>
        ))}
      </div>
    </div>
  )
}

function ErrorState({ message, onRetry, onUseOffline }: { message: string | null; onRetry: () => void; onUseOffline: () => void }) {
  return (
    <div role="alert" className="card flex flex-col items-center px-6 py-14 text-center">
      <span className="grid h-14 w-14 place-items-center rounded-2xl bg-rose-50 text-rose-600 dark:bg-rose-500/10 dark:text-rose-400">
        <AlertTriangle className="h-7 w-7" />
      </span>
      <h3 className="mt-5 text-xl font-bold">We couldn’t generate your plan</h3>
      <p className="mt-2 max-w-md text-slate-600 dark:text-slate-400">
        {message ?? 'The AI advisor is temporarily unavailable.'} Your numbers are still here — try again, or use our offline analysis instead.
      </p>
      <div className="mt-6 flex flex-col gap-3 sm:flex-row">
        <button
          type="button"
          onClick={onRetry}
          className="inline-flex h-11 items-center justify-center gap-2 rounded-xl bg-indigo-600 px-5 text-sm font-semibold text-white transition hover:-translate-y-px hover:bg-indigo-500"
        >
          <RotateCw className="h-4 w-4" /> Try again
        </button>
        <button
          type="button"
          onClick={onUseOffline}
          className="inline-flex h-11 items-center justify-center gap-2 rounded-xl border border-slate-200 bg-white px-5 text-sm font-semibold transition hover:border-slate-300 dark:border-white/10 dark:bg-white/5"
        >
          <WifiOff className="h-4 w-4" /> Use offline analysis
        </button>
      </div>
    </div>
  )
}
